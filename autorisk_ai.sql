-- Quality rating validating

SELECT
    MIN(QUALITY_RATING) AS MIN_RATING,
    MAX(QUALITY_RATING) AS MAX_RATING,
    ROUND(AVG(QUALITY_RATING), 2) AS AVG_RATING,
    COUNT_IF(QUALITY_RATING IS NULL) AS MISSING_RATINGS
FROM AUTO_MFG_DW.SUPPLY_CHAIN.SUPPLIERS;


SELECT
    MIN(QUALITY_RATING) AS MIN_QUALITY_RATING,
    MAX(QUALITY_RATING) AS MAX_QUALITY_RATING,
    ROUND(AVG(QUALITY_RATING), 2) AS AVG_QUALITY_RATING,
    COUNT(*) AS TOTAL_SUPPLIERS,
    COUNT_IF(QUALITY_RATING IS NULL) AS MISSING_QUALITY_RATINGS
FROM AUTO_MFG_DW.SUPPLY_CHAIN.SUPPLIERS;

SELECT
    MIN(ON_TIME_DELIVERY_PCT) AS MIN_ON_TIME_PCT,
    MAX(ON_TIME_DELIVERY_PCT) AS MAX_ON_TIME_PCT,
    ROUND(AVG(ON_TIME_DELIVERY_PCT), 2) AS AVG_ON_TIME_PCT,
    COUNT(*) AS TOTAL_SUPPLIERS,
    COUNT_IF(ON_TIME_DELIVERY_PCT IS NULL) AS MISSING_DELIVERY_RATINGS
FROM AUTO_MFG_DW.SUPPLY_CHAIN.SUPPLIERS;
