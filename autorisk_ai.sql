CREATE OR REPLACE VIEW
    AUTO_MFG_DW.ANALYTICS.PRODUCTION_RISK_VIEW
AS
SELECT
    SHIFT_TYPE,
    COUNT(*) AS SHIFT_COUNT,
    ROUND(AVG(UNITS_PRODUCED), 2) AS AVG_UNITS_PRODUCED,
    ROUND(AVG(UNITS_SCRAPPED), 2) AS AVG_UNITS_SCRAPPED,
    ROUND(AVG(DOWNTIME_MINUTES), 2) AS AVG_DOWNTIME_MINUTES,
    ROUND(AVG(EFFICIENCY_PCT), 2) AS AVG_EFFICIENCY_PCT,

    CASE
        WHEN AVG(UNITS_PRODUCED) < 160
            THEN 'INVESTIGATE'
        ELSE 'NORMAL'
    END AS PRODUCTION_RISK

FROM AUTO_MFG_DW.WORKFORCE.PRODUCTION_SHIFTS
GROUP BY SHIFT_TYPE;

