CREATE OR REPLACE VIEW AUTO_MFG_DW.ANALYTICS.SUPPLIER_RISK_VIEW AS
WITH supplier_defects AS (
    SELECT
        SUPPLIER_ID,
        COUNT(*) AS DEFECT_COUNT,
        COUNT_IF(UPPER(SEVERITY) = 'CRITICAL') AS CRITICAL_DEFECTS,
        COUNT_IF(UPPER(SEVERITY) = 'HIGH') AS HIGH_DEFECTS
    FROM AUTO_MFG_DW.QUALITY.DEFECTS
    WHERE SUPPLIER_ID IS NOT NULL
    GROUP BY SUPPLIER_ID
),
supplier_orders AS (
    SELECT
        SUPPLIER_ID,
        COUNT(*) AS PURCHASE_ORDER_COUNT,
        SUM(QUANTITY_ORDERED) AS TOTAL_QUANTITY_ORDERED
    FROM AUTO_MFG_DW.SUPPLY_CHAIN.PURCHASE_ORDERS
    GROUP BY SUPPLIER_ID
)
SELECT
    s.SUPPLIER_ID,
    s.SUPPLIER_CODE,
    s.SUPPLIER_NAME,
    s.SUPPLIER_TIER,
    s.STATE_CODE,
    s.COUNTRY_CODE,
    s.QUALITY_RATING,
    s.ON_TIME_DELIVERY_PCT,
    s.STATUS AS SUPPLIER_STATUS,

    COALESCE(d.DEFECT_COUNT, 0) AS DEFECT_COUNT,
    COALESCE(d.CRITICAL_DEFECTS, 0) AS CRITICAL_DEFECTS,
    COALESCE(d.HIGH_DEFECTS, 0) AS HIGH_DEFECTS,

    COALESCE(o.PURCHASE_ORDER_COUNT, 0)
        AS PURCHASE_ORDER_COUNT,
    COALESCE(o.TOTAL_QUANTITY_ORDERED, 0)
        AS TOTAL_QUANTITY_ORDERED,

    CASE
        WHEN UPPER(COALESCE(s.STATUS, '')) NOT IN ('ACTIVE')
            THEN 'REVIEW STATUS'
        WHEN COALESCE(d.CRITICAL_DEFECTS, 0) > 0
            THEN 'HIGH PRIORITY'
        WHEN COALESCE(d.HIGH_DEFECTS, 0) > 0
            THEN 'INVESTIGATE'
        WHEN s.QUALITY_RATING IS NOT NULL
             AND s.QUALITY_RATING < 3
            THEN 'INVESTIGATE'
        WHEN s.ON_TIME_DELIVERY_PCT IS NOT NULL
             AND s.ON_TIME_DELIVERY_PCT < 85
            THEN 'INVESTIGATE'
        ELSE 'NORMAL'
    END AS SUPPLIER_RISK

FROM AUTO_MFG_DW.SUPPLY_CHAIN.SUPPLIERS s
LEFT JOIN supplier_defects d
    ON s.SUPPLIER_ID = d.SUPPLIER_ID
LEFT JOIN supplier_orders o
    ON s.SUPPLIER_ID = o.SUPPLIER_ID;


SELECT *
FROM AUTO_MFG_DW.ANALYTICS.SUPPLIER_RISK_VIEW
ORDER BY
    CASE SUPPLIER_RISK
        WHEN 'HIGH PRIORITY' THEN 1
        WHEN 'INVESTIGATE' THEN 2
        WHEN 'REVIEW STATUS' THEN 3
        ELSE 4
    END,
    DEFECT_COUNT DESC
LIMIT 25;


CREATE OR REPLACE VIEW AUTO_MFG_DW.ANALYTICS.SUPPLIER_RISK_SCORE_VIEW AS
WITH normalized AS (
    SELECT
        *,
        /* Assumes QUALITY_RATING uses a 0-100 scale */
        GREATEST(0, LEAST(100,
            100 - COALESCE(QUALITY_RATING, 100)
        )) AS QUALITY_RISK_SCORE,

        GREATEST(0, LEAST(100,
            100 - COALESCE(ON_TIME_DELIVERY_PCT, 100)
        )) AS DELIVERY_RISK_SCORE,

        LEAST(100, COALESCE(CRITICAL_DEFECTS, 0) * 10)
            AS CRITICAL_RISK_SCORE,

        LEAST(100, COALESCE(HIGH_DEFECTS, 0) * 5)
            AS HIGH_DEFECT_RISK_SCORE
    FROM AUTO_MFG_DW.ANALYTICS.SUPPLIER_RISK_VIEW
)
SELECT
    SUPPLIER_ID,
    SUPPLIER_NAME AS COMPANY_NAME,
    SUPPLIER_RISK AS EXISTING_RISK_CATEGORY,
    QUALITY_RATING,
    ON_TIME_DELIVERY_PCT,
    DEFECT_COUNT,
    CRITICAL_DEFECTS,
    HIGH_DEFECTS,

    ROUND(
        0.25 * QUALITY_RISK_SCORE
      + 0.20 * DELIVERY_RISK_SCORE
      + 0.40 * CRITICAL_RISK_SCORE
      + 0.15 * HIGH_DEFECT_RISK_SCORE,
      1
    ) AS RISK_SCORE,

    CASE
        WHEN
            0.25 * QUALITY_RISK_SCORE
          + 0.20 * DELIVERY_RISK_SCORE
          + 0.40 * CRITICAL_RISK_SCORE
          + 0.15 * HIGH_DEFECT_RISK_SCORE >= 70
            THEN 'HIGH RISK'
        WHEN
            0.25 * QUALITY_RISK_SCORE
          + 0.20 * DELIVERY_RISK_SCORE
          + 0.40 * CRITICAL_RISK_SCORE
          + 0.15 * HIGH_DEFECT_RISK_SCORE >= 40
            THEN 'MEDIUM RISK'
        ELSE 'LOW RISK'
    END AS RISK_FACTOR

FROM normalized;

-- Supplier Risk
SELECT
    COMPANY_NAME,
    RISK_FACTOR,
    RISK_SCORE
FROM AUTO_MFG_DW.ANALYTICS.SUPPLIER_RISK_SCORE_VIEW
ORDER BY RISK_SCORE DESC
LIMIT 20;


SELECT
    COMPANY_NAME,
    RISK_SCORE,
    RISK_FACTOR,

    CASE
        WHEN RISK_FACTOR = 'HIGH RISK' THEN '#DC4545'
        WHEN RISK_FACTOR = 'MEDIUM RISK' THEN '#E6A23C'
        WHEN RISK_FACTOR = 'LOW RISK' THEN '#329764'
        ELSE '#808080'
    END AS COLOR_CODE

FROM AUTO_MFG_DW.ANALYTICS.SUPPLIER_RISK_SCORE_VIEW
ORDER BY RISK_SCORE DESC
LIMIT 20;


-- NOTE:
