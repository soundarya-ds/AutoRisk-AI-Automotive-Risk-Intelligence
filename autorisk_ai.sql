    COUNT(*) AS SHIFT_COUNT,
    ROUND(AVG(UNITS_PRODUCED), 2) AS AVG_UNITS,
    ROUND(AVG(UNITS_SCRAPPED), 2) AS AVG_SCRAPPED,
